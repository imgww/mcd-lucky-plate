"""餐品幸运清单：为每一道真实在售餐品列出可能的幸运寓意。

为什么要有这个文件
------------------
早期版本只有 `lucky.py` 里的主题词库——即「主题定义 anchor → 反查餐品」。
那个方向有一个结构性缺陷：**只有被某个主题用到的餐品才有寓意**，
其余一百多项（真实菜单共 154 项）白白浪费，用户问「我这杯燕麦奶有什么寓意」
时答不上来。

本文件把方向反过来：**先穷举全部餐品，为每项标注它能承载的寓意**，
主题再从清单里挑。带来三个好处：

1. **可查**：任何餐品都能回答「它有什么寓意」，不必是某个主题的专属
2. **可审**：寓意与谐音类型逐条写在数据里，可人工复核、可改后复跑
3. **可发现**：改完能立刻看出哪些餐品还没被任何主题用上

字段
----
kind    寓意类型
  homophone  谐音改写（鸡腿→吉）
  literal    字面吉祥义（巨无霸→气魄）
  brand      品牌自带官方梗（牛气满满）
  reverse    反向取意（浓缩→财富浓缩）
  none       无可行寓意（诚实留空，不硬凑）

score   寓意契合度 0-3，仅用于排序与人工判断，**不参与求解**：
  3 梗很硬，一听就成立
  2 成立，但需要解释一句
  1 牵强，取意空间大（默认不给，避免污染词库）

`note` 写明来源与边界，供审阅。**谐音仅限官方在售品名本身**，
不涉及谐音梗的二次创作边界说明。
"""

