def lookup(name: str) -> tuple[Luck, ...]:
    """查一道餐品的全部寓意；未收录返回空元组。"""
    return MENU_LUCK.get(name, ())


def best(name: str, min_score: int = 2) -> Luck | None:
    """取一道餐品契合度最高的寓意。"""
    lucks = [l for l in MENU_LUCK.get(name, ()) if l.score >= min_score]
    return max(lucks, key=lambda l: l.score) if lucks else None


def covered_foods(foods) -> tuple[str, ...]:
    """返回清单已覆盖的餐品名（按 foods 顺序）。"""
    return tuple(f.name for f in foods if f.name in MENU_LUCK)


def uncovered_foods(foods) -> tuple[str, ...]:
    """返回清单未覆盖的餐品名——这是需要补词库的清单。"""
    return tuple(f.name for f in foods if f.name not in MENU_LUCK)


def motifs_index() -> dict[str, tuple[str, ...]]:
    """反查索引：寓意 key → 拥有该寓意的餐品名列表。

    主题词库正是靠这个索引与清单对接的。
    """
    idx: dict[str, list[str]] = {}
    for name, lucks in MENU_LUCK.items():
        for l in lucks:
            idx.setdefault(l.key, []).append(name)
    return {k: tuple(sorted(v)) for k, v in sorted(idx.items())}